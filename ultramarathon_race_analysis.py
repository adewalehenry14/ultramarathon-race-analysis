"""Ultramarathon Race Analysis

Analysis of USA 50km and 50mi ultramarathons: how race distance, gender,
age and race month relate to athlete average speed (km/h).
"""

import os
import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

sns.set_theme(style='whitegrid')
os.makedirs('images', exist_ok=True)

# Cleaning thresholds (document these in your README)
MIN_AGE, MAX_AGE = 18, 90
MIN_SPEED, MAX_SPEED = 1, 20   # km/h; anything above 20 is faster than elite 50km pace

def save(name):
    plt.tight_layout()
    plt.savefig(f'images/{name}.png', dpi=150, bbox_inches='tight')
    plt.show()

# 1. LOAD DATA
# ---------------------------------------------------------------------------
df = pd.read_csv('/content/Two_Centuries Races.csv')
print(df.shape)
print(df.dtypes)

# 2. CLEAN DATA
# Only USA races, 50km or 50mi
# ---------------------------------------------------------------------------
country = df['Event name'].str.split('(').str.get(1).str.split(')').str.get(0)

df2 = df[
    df['Event distance/length'].isin(['50km', '50mi']) & (country == 'USA')
].copy()

# Remove "(USA)" from the event name
df2['Event name'] = df2['Event name'].str.split('(').str.get(0).str.strip()

# Age at the time of the race (uses the event year, not a fixed 2020)
df2['athlete_age'] = df2['Year of event'] - df2['Athlete year of birth']

# Remove the "h" from performance (e.g. "4:30:12 h" -> "4:30:12")
df2['Athlete performance'] = df2['Athlete performance'].str.split('h').str.get(0).str.strip()

# Drop columns we don't need
df2 = df2.drop(columns=['Athlete club', 'Athlete country',
                        'Athlete year of birth', 'Athlete age category'])

# Speed to numeric (bad values become NaN)
df2['Athlete average speed'] = pd.to_numeric(df2['Athlete average speed'], errors='coerce')

# Rename columns
df2 = df2.rename(columns={
    'Year of event': 'year',
    'Event dates': 'race_day',
    'Event name': 'race_name',
    'Event distance/length': 'race_length',
    'Event number of finishers': 'race_number_of_finishers',
    'Athlete performance': 'athlete_performance',
    'Athlete gender': 'athlete_gender',
    'Athlete average speed': 'athlete_average_speed',
    'Athlete ID': 'athlete_id',
})

# Null values and duplicates
print(df2.isna().sum())
df2 = df2.dropna().drop_duplicates().reset_index(drop=True)
df2['athlete_age'] = df2['athlete_age'].astype(int)

rows_before = len(df2)

# Remove unrealistic ages and speeds (data entry errors)
df2 = df2[df2['athlete_age'].between(MIN_AGE, MAX_AGE)]
df2 = df2[df2['athlete_average_speed'].between(MIN_SPEED, MAX_SPEED)]
print(f'Removed {rows_before - len(df2)} rows with unrealistic age or speed')

# Final column order
df3 = df2[['race_day', 'race_name', 'race_length', 'race_number_of_finishers',
           'athlete_id', 'athlete_gender', 'athlete_age',
           'athlete_performance', 'athlete_average_speed']].copy()

# ---------------------------------------------------------------------------
# 3. NEW COLUMNS
# ---------------------------------------------------------------------------

# Race month: the second-to-last piece works for single-day ("15.01.2020")
# and multi-day ("20.-21.01.2020") dates
df3['race_month'] = df3['race_day'].str.split('.').str.get(-2).astype(int)

# Pace in minutes per km (easier for runners to read than km/h)
df3['pace_min_km'] = 60 / df3['athlete_average_speed']

# Age groups
bins = [17, 29, 39, 49, 59, 69, 90]
labels = ['18-29', '30-39', '40-49', '50-59', '60-69', '70-90']
df3['age_group'] = pd.cut(df3['athlete_age'], bins=bins, labels=labels)

# Male/female only for gender comparisons (X has too few athletes)
df_mf = df3[df3['athlete_gender'].isin(['M', 'F'])]

# Quick checks (use these numbers in your README and resume)
print('\nTotal race results:', len(df3))
print('Unique athletes:', df3['athlete_id'].nunique())
print('\nRace month counts')
print(df3['race_month'].value_counts().sort_index())
print('\nResults by distance')
print(df3['race_length'].value_counts())
print('\nResults by gender (share)')
print(df3['athlete_gender'].value_counts(normalize=True).round(3))

# ---------------------------------------------------------------------------
# 4. CHARTS
# ---------------------------------------------------------------------------

# 4.1 Number of results by distance
plt.figure(figsize=(6, 4))
ax = sns.countplot(data=df3, x='race_length')
ax.set(title='Number of results by race distance',
       xlabel='Race distance', ylabel='Number of results')
save('race_count')

# 4.2 Results by distance and gender (side by side)
plt.figure(figsize=(7, 4))
ax = sns.countplot(data=df_mf, x='race_length', hue='athlete_gender',
                   hue_order=['M', 'F'])
ax.set(title='Results by race distance and gender',
       xlabel='Race distance', ylabel='Number of results')
ax.legend(title='Gender')
save('race_count_gender')

# 4.3 Speed distribution, 50mi
sns.displot(df3[df3['race_length'] == '50mi'], x='athlete_average_speed',
            kde=True, height=4, aspect=1.5)
plt.title('Average speed distribution (50mi)')
plt.xlabel('Average speed (km/h)')
save('speed_distribution_50mi')

# 4.4 Speed distribution, 50km
sns.displot(df3[df3['race_length'] == '50km'], x='athlete_average_speed',
            kde=True, height=4, aspect=1.5)
plt.title('Average speed distribution (50km)')
plt.xlabel('Average speed (km/h)')
save('speed_distribution_50km')

# 4.5 Violin plot, male vs female
plt.figure(figsize=(7, 5))
ax = sns.violinplot(data=df_mf, x='race_length', y='athlete_average_speed',
                    hue='athlete_gender', hue_order=['M', 'F'],
                    split=True, inner='quart', linewidth=1)
ax.set(title='Average speed by distance and gender',
       xlabel='Race distance', ylabel='Average speed (km/h)')
ax.legend(title='Gender')
save('speed_violin')

# 4.6 Age vs speed (sampled, transparent points to avoid overplotting)
sample = df_mf.sample(min(5000, len(df_mf)), random_state=42)
g = sns.lmplot(data=sample, x='athlete_age', y='athlete_average_speed',
               hue='athlete_gender', hue_order=['M', 'F'],
               scatter_kws={'alpha': 0.15, 's': 8}, height=5, aspect=1.4)
g.set_axis_labels('Athlete age', 'Average speed (km/h)')
g.figure.suptitle('Age vs average speed (sample of 5,000 results)', y=1.02)
g.savefig('images/age_vs_speed.png', dpi=150, bbox_inches='tight')
plt.show()

# 4.7 Average speed by age group and gender
plt.figure(figsize=(8, 4))
ax = sns.barplot(data=df_mf, x='age_group', y='athlete_average_speed',
                 hue='athlete_gender', hue_order=['M', 'F'], errorbar=None)
ax.set(title='Average speed by age group and gender',
       xlabel='Age group', ylabel='Average speed (km/h)')
ax.legend(title='Gender')
save('speed_by_age_group')

# 4.8 Speed by race month (Jan-Mar only; May has too few races)
plt.figure(figsize=(7, 4))
ax = sns.barplot(data=df3[df3['race_month'].isin([1, 2, 3])],
                 x='race_month', y='athlete_average_speed', errorbar=None)
ax.set_xticks([0, 1, 2])
ax.set_xticklabels(['Jan', 'Feb', 'Mar'])
ax.set(title='Average speed by race month',
       xlabel='Race month', ylabel='Average speed (km/h)')
save('speed_by_month')

# ---------------------------------------------------------------------------
# 5. QUESTIONS FROM THE DATA
# ---------------------------------------------------------------------------

# Difference in speed between male and female, 50km and 50mi
print('\nMean speed by distance and gender (km/h)')
print(df3.groupby(['race_length', 'athlete_gender'])['athlete_average_speed']
      .mean().round(2))

# Does the gender gap change with age?
print('\nSpeed by age group and gender')
print(df_mf.groupby(['age_group', 'athlete_gender'], observed=True)
      ['athlete_average_speed'].agg(['mean', 'count']).round(2))

# Best ages in the 50mi race (min 20 races), top 15
print('\nBest ages, 50mi (min 20 results)')
best = (df3.query('race_length == "50mi"')
        .groupby('athlete_age')['athlete_average_speed']
        .agg(['mean', 'count'])
        .query('count > 19')
        .sort_values('mean', ascending=False)
        .head(15))
print(best.round(2))

# Slowest ages in the 50mi race (min 10 races), bottom 20
print('\nSlowest ages, 50mi (min 10 results)')
worst = (df3.query('race_length == "50mi"')
         .groupby('athlete_age')['athlete_average_speed']
         .agg(['mean', 'count'])
         .query('count > 9')
         .sort_values('mean', ascending=True)
         .head(20))
print(worst.round(2))

# Does race month affect speed?
print('\nSpeed by race month, all races')
print(df3.groupby('race_month')['athlete_average_speed']
      .agg(['mean', 'count']).round(2))

print('\nSpeed by race month, 50mi only')
print(df3.query('race_length == "50mi"').groupby('race_month')['athlete_average_speed']
      .agg(['mean', 'count']).round(2))